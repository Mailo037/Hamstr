"""Builds the launcher shortcut icons (adaptive) from the app's Phosphor vectors,
and the widget's hamster mark.

    python tools/render_shortcuts.py
"""
import pathlib
import re

from render_icon import render

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
ICONS = ROOT / "shared/src/commonMain/composeResources/drawable"
ACCENT = "#FFFF9A3C"
GLYPH_DP = 44  # inside the 108 dp adaptive canvas, well within the 66 dp safe zone

SHORTCUTS = {"sc_paste": "ic_content_paste", "sc_add": "ic_add", "sc_library": "ic_grid_view"}

for name, icon in SHORTCUTS.items():
    src = (ICONS / f"{icon}.xml").read_text(encoding="utf-8")
    paths = "\n".join(
        f'        <path android:fillColor="{ACCENT}" android:pathData="{d}" />'
        for d in re.findall(r'android:pathData="([^"]+)"', src))
    scale = GLYPH_DP / float(re.search(r'android:viewportWidth="([\d.]+)"', src).group(1))
    offset = (108 - GLYPH_DP) / 2
    (RES / "drawable" / f"{name}_fg.xml").write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/render_shortcuts.py from {icon}.xml -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="{offset}" android:translateY="{offset}" android:scaleX="{scale:.6f}" android:scaleY="{scale:.6f}">
{paths}
    </group>
</vector>
''', encoding="utf-8")
    (RES / "drawable" / f"{name}.xml").write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/shortcut_background" />
    <foreground android:drawable="@drawable/{name}_fg" />
</adaptive-icon>
''', encoding="utf-8")

out = RES / "drawable-nodpi"
out.mkdir(exist_ok=True)
render(192, 0.92, background=False).save(out / "widget_mark.png")
print("ok")
