"""Renders the Hamstr ASCII mark (same grid as ui/components/HamstrMark.kt) to PNGs."""
import sys, pathlib
from PIL import Image, ImageDraw, ImageFont

GRID = [
    "...###....###...",
    "..#####..#####..",
    "...##########...",
    "..############..",
    ".##############.",
    ".##############.",
    "####0######0####",
    "################",
    "#***########***#",
    ".***########***.",
    "..############..",
    "....########....",
]
INK, ACCENT, BG = (238, 238, 238), (255, 154, 60), (10, 10, 9)
ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT = ROOT / "shared/src/commonMain/composeResources/font/jetbrains_mono_600.ttf"


# The launcher has one icon per accent preset (data/Prefs.kt ACCENTS); AppIcon picks the nearest.
PRESETS = {
    "": (255, 154, 60),
    "_pink": (255, 95, 210),
    "_lemon": (242, 213, 65),
    "_mint": (61, 220, 151),
    "_sky": (90, 180, 255),
    "_violet": (169, 139, 255),
    "_coral": (255, 107, 107),
}


def render(size, content_frac, background=True, accent=ACCENT, ink=INK):
    img = Image.new("RGBA", (size, size), BG + (255,) if background else (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    cols, rows = len(GRID[0]), len(GRID)
    cell = size * content_frac / cols
    font = ImageFont.truetype(str(FONT), int(cell * 1.15))
    ox, oy = (size - cell * cols) / 2, (size - cell * rows * 1.1) / 2
    for r, line in enumerate(GRID):
        for c, ch in enumerate(line):
            if ch == ".":
                continue
            color = accent if ch == "*" else ink
            d.text((ox + c * cell + cell / 2, oy + r * cell * 1.1 + cell * 0.55), ch, font=font, fill=color, anchor="mm")
    return img


def stat_vector():
    """The same grid as a one-colour vector for the status bar: every glyph becomes a
    solid cell, the eyes stay open and the cheeks turn into small dots."""
    cols, rows = len(GRID[0]), len(GRID)
    cell = 22 / cols
    pitch = cell * 1.1
    oy = (24 - pitch * rows) / 2
    f = lambda v: f"{v:.3f}".rstrip("0").rstrip(".")
    parts = []
    for r, line in enumerate(GRID):
        y = oy + r * pitch
        c = 0
        while c < cols:
            if line[c] in "#0":
                # Runs of solid cells merge so the rows touch; the eye cells are left out.
                start = c
                while c < cols and line[c] == "#":
                    c += 1
                if c > start:
                    x = 1 + start * cell
                    parts.append(f"M{f(x)},{f(y)}h{f((c - start) * cell)}v{f(pitch)}h{f(-(c - start) * cell)}z")
                if c < cols and line[c] == "0":
                    c += 1
            elif line[c] == "*":
                d = cell * 0.55
                x = 1 + c * cell + (cell - d) / 2
                parts.append(f"M{f(x)},{f(y + (pitch - d) / 2)}h{f(d)}v{f(d)}h{f(-d)}z")
                c += 1
            else:
                c += 1
    return "\n".join([
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Notification/monochrome mark: the launcher's ASCII hamster grid as solid cells. Generated by tools/render_icon.py. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp" android:height="24dp"',
        '    android:viewportWidth="24" android:viewportHeight="24">',
        '    <path android:fillColor="#FFFFFFFF"',
        f'        android:pathData="{" ".join(parts)}" />',
        "</vector>",
        "",
    ])


ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/icon_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground{suffix}" />
    <monochrome android:drawable="@drawable/ic_stat_hamstr_inset" />
</adaptive-icon>
"""


LIGHT_INK, ON_ACCENT = (26, 23, 20), (20, 16, 10)
STYLED = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="{background}" />
    <foreground android:drawable="@mipmap/{foreground}" />
    <monochrome android:drawable="@drawable/ic_stat_hamstr_inset" />
</adaptive-icon>
"""


def solid(size, content_frac, accent=ACCENT, ink=INK):
    """The grid as solid cells: the glyphs of the mark blur into grey at taskbar size, cells
    stay a hamster. Eyes are holes, cheeks are accent cells."""
    img = Image.new("RGBA", (size, size), BG + (255,))
    d = ImageDraw.Draw(img)
    cols, rows = len(GRID[0]), len(GRID)
    cell = size * content_frac / cols
    ox, oy = (size - cell * cols) / 2, (size - cell * rows) / 2
    for r, line in enumerate(GRID):
        for c, ch in enumerate(line):
            if ch in "#*":
                x, y = ox + c * cell, oy + r * cell
                d.rectangle([x, y, x + cell - 1, y + cell - 1], fill=accent if ch == "*" else ink)
    return img


def tiled(picture, size=1024, tile_frac=824 / 1024):
    """[picture] on a rounded tile; macOS draws its icons on 824 of 1024 px, Windows edge to edge."""
    tile, radius = round(size * tile_frac), round(size * tile_frac * 0.225)
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle([(size - tile) // 2] * 2 + [(size + tile) // 2 - 1] * 2, radius, fill=255)
    img.paste(picture, (0, 0), mask)
    return img


def desktop():
    """The desktop app's icons (desktop/icons): the ASCII mark where icons are big (the
    PNG Linux takes, the .icns macOS takes) and the solid cells where they are small (the
    .ico Windows takes, and the window's own icon in the title bar and taskbar)."""
    out = ROOT / "desktop/icons"
    out.mkdir(parents=True, exist_ok=True)
    mark = tiled(render(1024, 0.56))
    mark.save(out / "hamstr.png")
    mark.save(out / "hamstr.icns")
    small = tiled(solid(1024, 0.74), tile_frac=0.96)
    small.save(out / "hamstr.ico", sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    small.resize((256, 256), Image.LANCZOS).save(out / "hamstr_window.png")
    # The Windows setup's pictures (desktop/windows/hamstr.iss), at 100 % and 200 %: the mark
    # beside the first and last page, the small tile in the header of the others (white there).
    setup = ROOT / "desktop/windows"
    for k in (1, 2):
        side = Image.new("RGB", (164 * k, 314 * k), BG)
        side.paste(render(164 * k, 0.6).convert("RGB"), (0, (314 - 164) * k // 2))
        side.save(setup / f"setup_side_{k}x.bmp")
        header = Image.new("RGB", (55 * k, 55 * k), (255, 255, 255))
        tile = small.resize((55 * k, 55 * k), Image.LANCZOS)
        header.paste(tile, (0, 0), tile)
        header.save(setup / f"setup_small_{k}x.bmp")


if __name__ == "__main__":
    if sys.argv[1:] == ["desktop"]:
        desktop()
        print("ok")
        sys.exit()
    res = ROOT / "app/src/main/res"
    dens = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
    for suffix, accent in PRESETS.items():
        for name, k in dens.items():
            out = res / f"mipmap-{name}"
            out.mkdir(parents=True, exist_ok=True)
            # Adaptive foreground: 108dp canvas, mark inside the 66dp safe zone.
            render(int(108 * k), 0.52, background=False, accent=accent).save(out / f"ic_launcher_foreground{suffix}.png")
            # Legacy square icon for API 26 launchers that ignore adaptive icons.
            render(int(48 * k), 0.78, accent=accent).save(out / f"ic_launcher{suffix}.png")
        (res / f"mipmap-anydpi-v26/ic_launcher{suffix}.xml").write_text(ADAPTIVE.format(suffix=suffix), encoding="utf-8")
        # Light style: dark hamster with accent cheeks on a pale tile.
        for name, k in dens.items():
            render(int(108 * k), 0.52, background=False, accent=accent, ink=LIGHT_INK).save(res / f"mipmap-{name}/ic_launcher_foreground_light{suffix}.png")
        (res / f"mipmap-anydpi-v26/ic_launcher_light{suffix}.xml").write_text(
            STYLED.format(background="@color/icon_light", foreground=f"ic_launcher_foreground_light{suffix}"), encoding="utf-8")
        # Accent style: the tile is the accent, the hamster dark with white cheeks.
        (res / f"mipmap-anydpi-v26/ic_launcher_accent{suffix}.xml").write_text(
            STYLED.format(background=f"@color/icon_accent{suffix}", foreground="ic_launcher_foreground_onaccent"), encoding="utf-8")
    for name, k in dens.items():
        render(int(108 * k), 0.52, background=False, accent=(255, 255, 255), ink=ON_ACCENT).save(res / f"mipmap-{name}/ic_launcher_foreground_onaccent.png")
    colors = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Launcher tile colours for the icon styles. Generated by tools/render_icon.py. -->", "<resources>",
              '    <color name="icon_light">#FFF2EEE8</color>']
    colors += [f'    <color name="icon_accent{s}">#FF{a[0]:02X}{a[1]:02X}{a[2]:02X}</color>' for s, a in PRESETS.items()]
    (res / "values/icon_colors.xml").write_text("\n".join(colors + ["</resources>", ""]), encoding="utf-8")
    (res / "drawable/ic_stat_hamstr.xml").write_text(stat_vector(), encoding="utf-8")
    render(1024, 0.7).save(ROOT / "design/assets/icon_mark.png")
    desktop()
    print("ok")
